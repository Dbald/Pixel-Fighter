const CHAR_W = 5;
const CHAR_H = 5;

export class PixelFont {
    /**
     * Draw pixel-perfect text at the given position.
     * @param {CanvasRenderingContext2D} ctx
     * @param {string} text
     * @param {number} x
     * @param {number} y
     * @param {object} opts - { color, scale, align, shadow, shadowColor }
     */
    static draw(ctx, text, x, y, opts = {}) {
        const {
            color = '#FFF',
            scale = 1,
            align = 'center',
            shadow = false,
            shadowColor = '#000',
        } = opts;

        text = text.toUpperCase();
        const spacing = 1 * scale;
        const charW = CHAR_W * scale;
        const totalW = text.length * (charW + spacing) - spacing;

        let startX = x;
        if (align === 'center') startX = x - totalW / 2;
        else if (align === 'right') startX = x - totalW;

        startX = Math.round(startX);
        y = Math.round(y);

        if (shadow) {
            this._drawString(ctx, text, startX + scale, y + scale, shadowColor, scale, spacing);
        }
        this._drawString(ctx, text, startX, y, color, scale, spacing);
    }

    static _drawString(ctx, text, startX, y, color, scale, spacing) {
        ctx.fillStyle = color;
        let cx = startX;
        for (let c = 0; c < text.length; c++) {
            const ch = text[c];
            const bitmap = CHARS[ch];
            if (bitmap) {
                for (let row = 0; row < CHAR_H; row++) {
                    for (let col = 0; col < CHAR_W; col++) {
                        if (bitmap[row * CHAR_W + col]) {
                            ctx.fillRect(cx + col * scale, y + row * scale, scale, scale);
                        }
                    }
                }
            }
            cx += CHAR_W * scale + spacing;
        }
    }

    /**
     * Get the pixel width of a string at a given scale.
     */
    static measure(text, scale = 1) {
        const spacing = 1 * scale;
        const charW = CHAR_W * scale;
        return text.length * (charW + spacing) - spacing;
    }
}
